def normalize_mac(mac: str | None) -> str:
    if not mac:
        return ""
    cleaned = re.sub(r"[^0-9A-Fa-f]", "", mac).upper()
    if len(cleaned) != 12:
        return ""
    return ":".join(cleaned[i:i + 2] for i in range(0, 12, 2))


def is_randomized_mac(mac: str) -> bool:
    """Locally administered (bit 1 of the first octet) - phones randomise these."""
    mac = normalize_mac(mac)
    if not mac:
        return False
    first = int(mac.split(":")[0], 16)
    return bool(first & 0x02)


def is_multicast_mac(mac: str) -> bool:
    mac = normalize_mac(mac)
    if not mac:
        return False
    return bool(int(mac.split(":")[0], 16) & 0x01)


class VendorLookup:
    """OUI -> manufacturer, with optional user-supplied full registry."""

    def __init__(self) -> None:
        self._table: dict[str, str] = {}
        for prefix, vendor in OUI_TABLE.items():
            cleaned = prefix.replace(":", "").replace(" ", "").upper()
            if len(cleaned) == 6:
                self._table.setdefault(cleaned, vendor.strip())
        self.source = f"bundled subset ({len(self._table)} prefixes)"

    def load_file(self, path: Path | str) -> int:
        """Load an IEEE ``oui.csv`` or ``manuf`` style file; returns entries added."""
        added = 0
        text = Path(path).read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            line = line.strip()
            if not line or line.lower().startswith("registry"):
                continue
            prefix = vendor = ""
            if "," in line:
                parts = line.split(",")
                if len(parts) >= 2:
                    prefix = parts[1] if len(parts[0]) > 6 else parts[0]
                    vendor = parts[2] if len(parts) > 2 else parts[-1]
            elif "\t" in line:
                prefix, _, vendor = line.partition("\t")
            elif " " in line:
                prefix, _, vendor = line.partition(" ")
            cleaned = re.sub(r"[^0-9A-Fa-f]", "", prefix.strip())[:6].upper()
            if len(cleaned) == 6 and vendor.strip():
                if cleaned not in self._table:
                    added += 1
                self._table[cleaned] = vendor.strip().strip('"')
        self.source = f"bundled subset + imported file ({len(self._table)} prefixes)"
        return added

    @property
    def size(self) -> int:
        return len(self._table)

    def lookup(self, mac: str | None) -> str | None:
        mac = normalize_mac(mac)
        if not mac:
            return None
        prefix = mac.replace(":", "")[:6]
        vendor = self._table.get(prefix)
        if vendor:
            return vendor
        if is_randomized_mac(mac):
            return "Private / randomised MAC"
        return None
